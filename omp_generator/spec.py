"""Load the OpenMP specification sources into the normalized model (:mod:`.model`).

Inputs, relative to the root of the specification sources:

* ``json/{directive,clause,clause-group,modifier,modifier-group}/*.json``
* ``appendices/grammar_compound_directives.tex``: grammar of compound directive names
* ``version.mk``: OpenMP version

Only structural facts are read. Prose (``additional_info``, section names, index entries,
cross references, source file names) is deliberately ignored, so that the generated code
does not contain any text of the specification.
"""

from __future__ import annotations

import json
import pathlib
import re
import subprocess
from typing import Dict, Iterable, List, Optional, Tuple

from . import compound
from .model import (
    COMPLEX,
    DIRECTIVE_NAME,
    DIRECTIVE_SPECIFICATION,
    EXPRESSION,
    IDENTIFIER,
    KEYWORD,
    LIST,
    LIST_ITEM,
    STYLIZED,
    TYPE_NAME,
    VARIABLE,
    Argument,
    Clause,
    ClauseGroup,
    Directive,
    MemberSet,
    Modifier,
    ModifierGroup,
    Spec,
)

# Clause-groups whose members are directive names rather than clauses, and the directive
# property that selects those directives. This is not encoded in the JSON sources.
DIRECTIVE_NAME_CLAUSE_GROUPS = {
    "cancel-directive-name": "cancellable",
}

IDENTIFIER_TYPES = {"identifier", "base language identifier", "OpenMP identifier"}

# "modifying" values meaning "all the arguments of the clause"
ALL_ARGUMENTS = {"", "all arguments"}


class SpecError(Exception):
    pass


def _strip_article(t: str) -> str:
    """'An OpenMP reduction identifier' -> 'OpenMP reduction identifier'"""
    return re.sub(r"^(An|A)\s+", "", t.strip())


def _tuple(x: Optional[Iterable[str]]) -> Tuple[str, ...]:
    return tuple(x) if x else ()


def _union(*xs: Iterable[str]) -> Tuple[str, ...]:
    out: List[str] = []
    for x in xs:
        for e in x or ():
            if e not in out:
                out.append(e)
    return tuple(out)


def _spelling(raw: dict) -> str:
    return raw.get("$clean_name", raw["$name"]).strip().replace(" ", "_")


class Loader:
    def __init__(self, root: pathlib.Path):
        self.root = pathlib.Path(root)
        self.json = self.root / "json"
        if not self.json.is_dir():
            raise SpecError(f"{self.json} is not a directory: is {self.root} the root of the OpenMP spec sources?")
        self.warnings: List[str] = []
        self.raw: Dict[str, Dict[str, dict]] = {}
        # names of the loops generated by loop-transforming directives (see `apply`)
        self.generated_loop_names: Tuple[str, ...] = ()

    def warn(self, msg: str):
        self.warnings.append(msg)

    # -- raw JSON ------------------------------------------------------------------------

    def load_raw(self, kind: str) -> Dict[str, dict]:
        out: Dict[str, dict] = {}
        for f in sorted((self.json / kind).glob("*.json")):
            try:
                raw = json.loads(f.read_text(encoding="utf-8"))
            except json.JSONDecodeError as e:
                raise SpecError(f"{f}: invalid JSON: {e}") from e
            name = raw.get("$name")
            if not name:
                raise SpecError(f"{f}: missing $name")
            if raw.get("$type") != kind:
                self.warn(f"{f.name}: $type is {raw.get('$type')!r}, expected {kind!r}")
            out[name] = raw
        self.raw[kind] = out
        return out

    # -- syntax --------------------------------------------------------------------------

    def argument(self, raw: dict, name: Optional[str] = None) -> Argument:
        """Syntax of an argument / modifier value / list item from its JSON description
        (a dict with ``$type``, and optionally ``$name``, ``items``, ``properties``)."""
        name = raw.get("$name", name) or ""
        props = _tuple(raw.get("properties"))
        t = raw.get("$type", "")
        items = raw.get("items")
        items = items if isinstance(items, dict) else {}

        if t == "keyword":
            values = items.get("values", ())
            keyword = items.get("$keyword")
            if not values and keyword == "directive-name":
                return Argument(name, DIRECTIVE_NAME, keyword=keyword, properties=props)
            return Argument(name, KEYWORD, keyword=keyword, values=tuple(values), properties=props)

        if t == "complex":
            keyword = items.get("$keyword")
            values: Tuple[str, ...] = ()
            if items.get("$type") == "keyword":
                # complex modifier whose keyword is one of several values
                vs = (items.get("items") or {}).get("values", ())
                if isinstance(vs, str):
                    # placeholder, filled by the spec's own tooling with the names of the
                    # loops generated by loop-transforming directives
                    vs = self.generated_loop_names
                values = tuple(vs)
            args = tuple(self.argument(a) for a in items.get("arguments", ()))
            return Argument(name, COMPLEX, keyword=keyword, values=values, arguments=args, properties=props)

        if t == "list":
            item = self.list_item(items, name)
            return Argument(name, LIST, type=item.type, items=item, properties=props)

        kind, typ = self.classify(t, items)
        return Argument(name, kind, type=typ, properties=props)

    def classify(self, t: str, items: dict) -> Tuple[str, str]:
        """(kind, OpenMP type) of a non-keyword, non-complex, non-list type."""
        inner = items.get("$type", "") if items else ""
        if t == "expression":
            return EXPRESSION, inner
        if t == "variable":
            return VARIABLE, inner
        if t in IDENTIFIER_TYPES:
            return IDENTIFIER, inner or t
        if t == "directive-specification list item":
            return DIRECTIVE_SPECIFICATION, t
        if t == "directive-name list item":
            return DIRECTIVE_NAME, t
        if t == "type name":
            return TYPE_NAME, t
        if t.endswith("list item"):
            return LIST_ITEM, t
        if t in ("integer", "string"):
            return EXPRESSION, t
        return STYLIZED, _strip_article(t)

    def list_item(self, items: dict, list_name: str) -> Argument:
        if not items:
            return Argument("item", LIST_ITEM)
        t = items.get("$type", "")
        sub = items.get("items") if isinstance(items.get("items"), dict) else {}
        if t == "keyword" or "$keyword" in items:
            return Argument("item", KEYWORD, keyword=items.get("$keyword"), values=_tuple(items.get("values")))
        kind, typ = self.classify(t, sub)
        return Argument("item", kind, type=typ)

    def modifying(self, raw: dict) -> Tuple[str, ...]:
        m = raw.get("modifying")
        if m is None or m.strip() in ALL_ARGUMENTS:
            return ()
        return tuple(x.strip() for x in m.split(",") if x.strip())

    # -- entities ------------------------------------------------------------------------

    def global_modifier(self, raw: dict) -> Modifier:
        name = raw["$name"]
        mtype = dict(raw.get("modifier type") or {})
        mtype.setdefault("$name", name)
        return Modifier(
            name=name,
            value=self.argument(mtype, name),
            modifying=self.modifying(raw),
            properties=_tuple(raw.get("properties")),
        )

    def clause_modifier(self, owner: str, raw: dict, modifiers: Dict[str, Modifier]) -> Modifier:
        name = raw["$name"]
        if raw.get("$type") == "reference":
            base = modifiers.get(name)
            if base is None:
                raise SpecError(f"{owner}: reference to unknown modifier {name!r}")
            return Modifier(
                name=name,
                value=base.value,
                modifying=self.modifying(raw) if "modifying" in raw else base.modifying,
                properties=_union(base.properties, raw.get("properties")),
                reference=name,
            )
        value = self.argument({k: v for k, v in raw.items() if k not in ("properties", "modifying")}, name)
        return Modifier(name=name, value=value, modifying=self.modifying(raw), properties=_tuple(raw.get("properties")))

    def member_sets(self, owner: str, raw, key: str, what: str) -> Tuple[MemberSet, ...]:
        if not raw:
            return ()
        sets = [raw] if isinstance(raw, dict) else list(raw)
        out = []
        for i, s in enumerate(sets):
            name = s.get("$name") or s.get("name") or (f"{owner}-{what}" + (f"-{i + 1}" if len(sets) > 1 else ""))
            out.append(MemberSet(name=name, members=_tuple(s.get(key)), properties=_tuple(s.get("properties"))))
        return tuple(out)


def _git_revision(root: pathlib.Path) -> Optional[str]:
    try:
        r = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return r.stdout.strip() or None
    except (OSError, subprocess.CalledProcessError):
        return None


def _version(root: pathlib.Path) -> str:
    f = root / "version.mk"
    if f.is_file():
        m = re.search(r"^OMPVERSION\s*=\s*(?:Version\s*)?(\S+)", f.read_text(encoding="utf-8"), re.M)
        if m:
            return m.group(1)
    return "unknown"


def load(root, *, revision: Optional[str] = None, with_revision: bool = True) -> Spec:
    """Load the specification sources rooted at ``root``."""
    root = pathlib.Path(root)
    L = Loader(root)
    rdirs = L.load_raw("directive")
    rclauses = L.load_raw("clause")
    rgroups = L.load_raw("clause-group")
    rmods = L.load_raw("modifier")
    rmgroups = L.load_raw("modifier-group")

    L.generated_loop_names = tuple(
        sorted({n for d in rdirs.values() for k in ("genloops", "gennests") for n in (d.get(k) or {})})
    )

    spec = Spec(
        version=_version(root),
        revision=(revision or (_git_revision(root) if with_revision else None)),
    )

    # modifiers ---------------------------------------------------------------------------
    for name, raw in rmods.items():
        spec.modifiers[name] = L.global_modifier(raw)

    for name, raw in rmgroups.items():
        members = _tuple(raw.get("modifier-names"))
        for m in members:
            if m not in spec.modifiers:
                raise SpecError(f"modifier-group {name}: unknown modifier {m!r}")
        spec.modifier_groups[name] = ModifierGroup(
            name=name,
            modifiers=members,
            clauses=_tuple(raw.get("clauses")),
            properties=_tuple(raw.get("properties")),
        )

    # clauses -----------------------------------------------------------------------------
    for name, raw in rclauses.items():
        mods = [L.clause_modifier(name, m, spec.modifiers) for m in raw.get("modifiers", ())]
        sets = list(L.member_sets(name, raw.get("modifier set"), "modifier-names", "modifier-set"))
        for g in raw.get("modifier-groups", ()):
            group = spec.modifier_groups.get(g)
            if group is None:
                raise SpecError(f"clause {name}: unknown modifier-group {g!r}")
            have = {m.name for m in mods}
            for m in group.modifiers:
                if m not in have:
                    base = spec.modifiers[m]
                    mods.append(Modifier(m, base.value, base.modifying, base.properties, reference=m))
            sets.append(MemberSet(name=g, members=group.modifiers, properties=group.properties))
        names = {m.name for m in mods}
        for s in sets:
            for m in s.members:
                if m not in names:
                    L.warn(f"clause {name}: modifier-set {s.name} member {m!r} is not a modifier of the clause")
        spec.clauses[name] = Clause(
            name=name,
            spelling=_spelling(raw),
            arguments=tuple(L.argument(a) for a in raw.get("arguments", ())),
            modifiers=tuple(mods),
            modifier_sets=tuple(sets),
            directives=_tuple(raw.get("directives")),
            properties=_tuple(raw.get("properties")),
        )

    # clause groups -----------------------------------------------------------------------
    for name, raw in rgroups.items():
        members = _tuple(raw.get("clause-names"))
        member_property = None
        if any(m not in spec.clauses for m in members):
            member_property = DIRECTIVE_NAME_CLAUSE_GROUPS.get(name)
            if member_property is None or members != (name,):
                raise SpecError(f"clause-group {name}: members {members} are not clauses")
            members = ()
        spec.clause_groups[name] = ClauseGroup(
            name=name,
            clauses=members,
            directives=_tuple(raw.get("directives")),
            properties=_tuple(raw.get("properties")),
            arguments=tuple(L.argument(a) for a in raw.get("arguments", ())),
            modifiers=tuple(L.clause_modifier(name, m, spec.modifiers) for m in raw.get("modifiers", ())),
            member_property=member_property,
        )

    # directives --------------------------------------------------------------------------
    for name, raw in rdirs.items():
        d = Directive(
            name=name,
            spelling=_spelling(raw),
            category=raw.get("category", ""),
            association=raw.get("association", ""),
            association_properties=_tuple(raw.get("association properties")),
            arguments=tuple(L.argument(a) for a in raw.get("arguments", ())),
            clauses=_tuple(raw.get("clauses")),
            clause_groups=_tuple(raw.get("clause-groups")),
            clause_sets=L.member_sets(name, raw.get("clause set"), "clause-names", "clause-set"),
            properties=_tuple(raw.get("properties")),
            language=raw.get("lang_specific", "any"),
            separating=_tuple(raw.get("separating directives")),
            separated=_tuple(raw.get("separated directives")),
            subsidiary=_tuple(raw.get("subsidiary directives")),
            enclosing=_tuple(raw.get("enclosing directives")),
        )
        spec.directives[name] = d

    _check(spec, L)

    # compound directives -----------------------------------------------------------------
    grammar = root / "appendices" / "grammar_compound_directives.tex"
    if grammar.is_file():
        spec.compound_directives = compound.compound_directives(grammar.read_text(encoding="utf-8"))
        known = {d.spelling for d in spec.directives.values()}
        for c in spec.compound_directives:
            for leaf in c:
                if leaf not in known:
                    raise SpecError(f"compound directive {' '.join(c)}: unknown leaf directive {leaf!r}")
    else:
        L.warn(f"{grammar} not found: no compound directives")

    spec.warnings = L.warnings
    return spec


def _check(spec: Spec, L: Loader):
    """Cross-reference checks: fail on dangling references, warn on asymmetries."""
    for d in spec.directives.values():
        for c in d.clauses:
            if c not in spec.clauses:
                raise SpecError(f"directive {d.name}: unknown clause {c!r}")
        for g in d.clause_groups:
            if g not in spec.clause_groups:
                raise SpecError(f"directive {d.name}: unknown clause-group {g!r}")
        allowed = set(d.clauses) | {c for g in d.clause_groups for c in spec.clause_groups[g].clauses}
        for s in d.clause_sets:
            for c in s.members:
                if c not in allowed:
                    L.warn(f"directive {d.name}: clause-set {s.name} member {c!r} is not a clause of the directive")
    for c in spec.clauses.values():
        for dn in c.directives:
            d = spec.directives.get(dn)
            if d is None:
                raise SpecError(f"clause {c.name}: unknown directive {dn!r}")
            via_group = any(c.name in spec.clause_groups[g].clauses for g in d.clause_groups)
            if c.name not in d.clauses and not via_group:
                L.warn(f"clause {c.name} lists directive {dn} which does not list it")
    for g in spec.clause_groups.values():
        for dn in g.directives:
            if dn not in spec.directives:
                raise SpecError(f"clause-group {g.name}: unknown directive {dn!r}")
